'use strict';
// One maintained translation engine. Generate the loadable extension without GM metadata,
// network dependencies or modifications to the independently installable userscript.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const source = read(path.join(root, 'HentaiVerse-Chinese.user.js'));
const header = source.match(/^\/\/ ==UserScript==\n[\s\S]*?^\/\/ ==\/UserScript==\n/m);
if (!header || header.index !== 0) throw Error('Missing userscript metadata');
const meta = key => header[0].match(new RegExp(`^//\\s+@${key}\\s+(.+)$`, 'm'))[1];
const content = `// Generated by scripts/build-hv-extension.cjs from HentaiVerse-Chinese ${meta('version')}.\n`
    + `// ${meta('author')} | ${meta('license')}\n` + source.slice(header[0].length);
const matches = [...header[0].matchAll(/^\/\/\s+@match[^\S\n]+(\S+)$/gm)].map(m => m[1]);
if (!matches.length) throw Error('No @match entries in userscript metadata');
const version = '1.2.3';
const icons = Object.fromEntries([16, 32, 48, 128].map(size => [size, `icon-${size}.png`]));
const manifest = {
    manifest_version: 3,
    name: 'HentaiVerse 简体中文',
    description: '汉化 HentaiVerse 游戏界面、战斗日志，以及论坛和拍卖站中已适配的装备名称与词缀。',
    version, icons,
    update_url: 'https://meiyongai.github.io/JPX-PLUS/extensions/updates.xml',
    version_name: `${version} · 汉化 ${meta('version')}`,
    action: {default_icon: icons, default_popup: 'popup.html', default_title: 'HentaiVerse 汉化 · 版本与更新'},
    permissions: ['alarms', 'storage'],
    background: {service_worker: 'updates.js'},
    minimum_chrome_version: '111',
    content_scripts: [{matches, js: ['translate.js'], world: 'MAIN', run_at: 'document_start', all_frames: true}]
};
for (const [name, data] of [['manifest.json', JSON.stringify(manifest, null, 2) + '\n'], ['translate.js', content]]) {
    const output = path.join(root, 'extensions/hv-zh-cn', name);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(output) || read(output) !== data) throw Error(`${name} is stale; run npm run build:hv-extension`);
    } else fs.writeFileSync(output, data);
}
